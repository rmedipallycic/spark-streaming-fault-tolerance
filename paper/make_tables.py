"""Generate every table, figure data file and in-text number of the paper from
the committed trial records. Nothing in paper/tables/ is typed by hand.

Reads   experiments/live/      first study: sinks x failures, strategies A and B
        experiments/live_acs/  ACS comparison, first run
        experiments/live_acs2/ ACS comparison, second (interleaved) run
Writes  paper/tables/*.tex and paper/tables/frontier_run*.dat

    python paper/make_tables.py
"""
import glob
import json
import os
import re
import statistics
import sys
from collections import defaultdict

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "live"))
from analyze_acs import STALL_S, label, producer_overrun  # noqa: E402

OUT = os.path.join(REPO, "paper", "tables")
ORDER = ["A", "C (3.3 s)", "ACS v2", "C (5.8 s)", "ACS v1", "B"]
MACRO_NAME = {"A": "A", "B": "B", "C (3.3 s)": "Cthree", "C (5.8 s)": "Cfive",
              "ACS v1": "AcsOne", "ACS v2": "AcsTwo"}
SHORT = {"A": "A (1 s)", "B": "B (30 s)", "C (3.3 s)": "C (3.3 s)", "C (5.8 s)": "C (5.8 s)",
         "ACS v1": "ACS v1", "ACS v2": "ACS v2"}


def load(sub):
    out = []
    for f in sorted(glob.glob(os.path.join(REPO, "experiments", sub, "*", "trial.json"))):
        with open(f, encoding="utf-8") as fh:
            r = json.load(fh)
        if r.get("run_type") != "measured":
            continue
        r["_dir"] = os.path.dirname(f)
        out.append(r)
    return out


def med(xs):
    xs = [x for x in xs if x is not None]
    return statistics.median(xs) if xs else None


def rng(xs, fmt):
    xs = [x for x in xs if x is not None]
    if not xs:
        return "--"
    m = statistics.median(xs)
    return f"{fmt.format(m)} ({fmt.format(min(xs))}--{fmt.format(max(xs))})"


def header(f):
    f.write("% generated by paper/make_tables.py from the committed trial records; do not edit\n")


def write(name, text):
    with open(os.path.join(OUT, name), "w", encoding="utf-8") as f:
        header(f)
        f.write(text)


def restart_split(r):
    """(Spark start-up, first batch) seconds of the restart after the kill, from spark.log."""
    ev = r["events"]
    if not ev.get("first_commit_after_restart"):
        return None
    try:
        with open(os.path.join(r["_dir"], "spark.log"), encoding="utf-8", errors="replace") as f:
            starts = [float(x) for x in re.findall(r"STREAM_STARTED (\d+\.\d+)", f.read())]
    except OSError:
        return None
    s2 = [x for x in starts if x > ev["job_start_2"]]
    if not s2:
        return None
    return s2[0] - ev["job_start_2"], ev["first_commit_after_restart"] - s2[0]


def main():
    os.makedirs(OUT, exist_ok=True)
    macros = {}

    # ------------------------------------------------------------------ study 1
    s1 = load("live")
    g = defaultdict(list)
    for r in s1:
        c = r["config"]
        g[(c["failure"], c["sink"], c["strategy"])].append(r)
    rows = []
    fail_name = {"none": "none (baseline)", "driver_failure": "driver kill",
                 "checkpoint_corruption": "offset-log corruption"}
    for fl in ("driver_failure", "checkpoint_corruption", "none"):
        for sk in ("file", "foreachbatch"):
            for st in ("A", "B"):
                ts = g.get((fl, sk, st), [])
                if not ts:
                    continue
                outs = defaultdict(int)
                for r in ts:
                    outs[r["outcome"]] += 1
                ok = [r for r in ts if r["outcome"] == "ok"]
                dups = [r["committed"]["duplicate_rows"] for r in ts]
                miss = [r["committed"]["missing_records"] for r in ok]
                rows.append(
                    f"{fail_name[fl]} & {'file' if sk == 'file' else 'foreachBatch'} & {SHORT[st]} & {len(ts)} & "
                    f"{', '.join(f'{o.replace(chr(95), chr(32))} {n}' for o, n in sorted(outs.items()))} & "
                    f"{sum(d > 0 for d in dups)} & {max(dups)} & "
                    f"{sum(m > 0 for m in miss)}/{len(ok)} & "
                    f"{rng([r['events'].get('recovery_latency_s') for r in ts], '{:.1f}')} \\\\\n")
    write("study1.tex", "".join(rows))
    kills = [r for r in s1 if r["config"]["failure"] == "driver_failure"]
    s1_rec = [r["events"]["recovery_latency_s"] for r in kills if r["events"].get("recovery_latency_s")]
    macros.update({
        "SOneTrials": len(s1),
        "SOneCommits": ", ".join(sorted({r["environment"]["git_commit"][:7] for r in s1})),
        "SOneRecMin": f"{min(s1_rec):.1f}", "SOneRecMax": f"{max(s1_rec):.1f}",
        "SOneCorruptFailed": sum(r["outcome"] == "restart_failed" for r in s1
                                 if r["config"]["failure"] == "checkpoint_corruption"),
        "SOneCorrupt": sum(r["config"]["failure"] == "checkpoint_corruption" for r in s1),
    })

    def startup_share(r):
        """Share of kill -> first commit spent before the restarted query was running."""
        sp = restart_split(r)
        ev = r["events"]
        if not sp or not ev.get("recovery_latency_s"):
            return None
        return (ev["job_start_2"] + sp[0] - ev["kill"]) / ev["recovery_latency_s"]
    sh = [x for x in (startup_share(r) for r in kills) if x is not None]
    macros["SOneStartupShareMed"] = f"{100 * statistics.median(sh):.0f}"
    macros["SOneStartupShareMin"] = f"{100 * min(sh):.0f}"
    macros["SOneStartupShareN"] = len(sh)

    # simulated (src/adaptive_checkpoint.py output) versus measured, driver failure
    import csv
    sim = {}
    with open(os.path.join(REPO, "experiments", "experiments", "adaptive", "adaptive_summary.csv"),
              encoding="utf-8") as f:
        for row in csv.DictReader(f):
            sim[(row["strategy"], row["scenario"])] = row
    rows = []
    for st, simname in (("A", "Strategy A (1s)"), ("B", "Strategy B (30s)")):
        sd = sim[(simname, "driver_failure")]
        meas = {}
        for sk in ("file", "foreachbatch"):
            ts = g[("driver_failure", sk, st)]
            meas[sk] = 100 * statistics.mean(r["committed"]["duplicate_rows"] / r["produced_acked"] for r in ts)
        rec = med([r["events"].get("recovery_latency_s") for sk in ("file", "foreachbatch")
                   for r in g[("driver_failure", sk, st)]])
        rows.append(f"{SHORT[st]} & {float(sd['duplicate_rate_mean_pct']):.2f} & "
                    f"{float(sd['recovery_latency_mean_ms']) / 1000:.1f} & {meas['file']:.2f} & "
                    f"{meas['foreachbatch']:.3f} & {rec:.1f} \\\\\n")
    write("sim_vs_measured.tex", "".join(rows))
    sc = sim[("Strategy B (30s)", "checkpoint_corruption")]
    macros["SimCorruptDupB"] = f"{float(sc['duplicate_rate_mean_pct']):.2f}"
    macros["SimCorruptDupA"] = f"{float(sim[('Strategy A (1s)', 'checkpoint_corruption')]['duplicate_rate_mean_pct']):.2f}"
    macros["SimAcsDup"] = f"{float(sim[('Adaptive (proposed)', 'driver_failure')]['duplicate_rate_mean_pct']):.3f}"

    # ------------------------------------------------------------------ ACS runs
    runs = {"1": load("live_acs"), "2": load("live_acs2")}
    clean, stalled = {}, {}
    for k, rs in runs.items():
        clean[k] = [r for r in rs if not ((producer_overrun(r) or 0) > STALL_S)]
        stalled[k] = [r for r in rs if (producer_overrun(r) or 0) > STALL_S]
    by = {k: defaultdict(list) for k in runs}
    for k in runs:
        for r in clean[k]:
            by[k][label(r["config"])].append(r)

    def m_lat(r, q):
        return (r.get("latency") or {}).get(q)

    # main table: second run
    rows = []
    for st in ORDER:
        ts = by["2"][st]
        ctl = [(r.get("control") or {}) for r in ts]
        mi = [c.get("time_weighted_interval_s") for c in ctl]
        rows.append(
            f"{SHORT[st]} & {len(ts)} & {rng([m_lat(r, 'p50_s') for r in ts], '{:.2f}')} & "
            f"{rng([m_lat(r, 'p95_s') for r in ts], '{:.2f}')} & "
            f"{rng([r.get('n_batch_commits') for r in ts], '{:.0f}')} & "
            f"{rng(mi, '{:.1f}') if any(mi) else '--'} & "
            f"{rng([c.get('switches') for c in ctl], '{:.0f}') if st.startswith('ACS') else '--'} & "
            f"{rng([r['events'].get('recovery_latency_s') for r in ts], '{:.1f}')} \\\\\n")
    write("acs_run2.tex", "".join(rows))

    # replication: both runs, medians
    rows = []
    for st in ORDER:
        cells = []
        for k in ("1", "2"):
            ts = by[k][st]
            cells += [f"{med([m_lat(r, 'p50_s') for r in ts]):.2f}", f"{med([m_lat(r, 'p95_s') for r in ts]):.2f}",
                      f"{med([r.get('n_batch_commits') for r in ts]):.0f}"]
        rows.append(f"{SHORT[st]} & " + " & ".join(cells) + " \\\\\n")
    write("acs_both.tex", "".join(rows))

    # frontier data (median commits vs median latency)
    for k in ("1", "2"):
        lines = ["strategy commits p50 p95 fixed"]
        for st in ORDER:
            ts = by[k][st]
            lines.append(f"{st.replace(' ', '').replace('(', '').replace(')', '')} "
                         f"{med([r.get('n_batch_commits') for r in ts]):.1f} "
                         f"{med([m_lat(r, 'p50_s') for r in ts]):.3f} {med([m_lat(r, 'p95_s') for r in ts]):.3f} "
                         f"{0 if st.startswith('ACS') else 1}")
        with open(os.path.join(OUT, f"frontier_run{k}.dat"), "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")
        place = {"A": "above", "B": "right", "C (3.3 s)": "below left", "C (5.8 s)": "below left",
                 "ACS v1": "above right", "ACS v2": "above right"}
        nodes = []
        for st in ORDER:
            ts = by[k][st]
            nodes.append(f"\\node[font=\\scriptsize, {place[st]}] at (axis cs:"
                         f"{med([r.get('n_batch_commits') for r in ts]):.1f},"
                         f"{med([m_lat(r, 'p50_s') for r in ts]):.3f}) {{{SHORT[st]}}};\n")
        write(f"frontier_labels_run{k}.tex", "".join(nodes))

    # paired comparison: trial t has the same input schedule and kill time for every strategy
    rows = []
    for k in ("1", "2"):
        d = {(label(r["config"]), r["config"]["trial"]): r for r in clean[k]}
        for a, b in (("ACS v2", "C (3.3 s)"), ("ACS v1", "C (5.8 s)")):
            ts = [t for t in range(10) if (a, t) in d and (b, t) in d]
            lo = lambda f: sum(f(d[(a, t)]) < f(d[(b, t)]) for t in ts)  # noqa: E731
            w50 = lo(lambda r: m_lat(r, "p50_s"))
            w95 = lo(lambda r: m_lat(r, "p95_s"))
            wc = lo(lambda r: r.get("n_batch_commits"))
            rows.append(f"{k} & {SHORT[a]} vs {SHORT[b]} & {w50}/{len(ts)} & {w95}/{len(ts)} & {wc}/{len(ts)} \\\\\n")
            tag = MACRO_NAME[a] + ("One" if k == "1" else "Two")
            macros[f"PairPfifty{tag}"] = f"{w50}/{len(ts)}"
            macros[f"PairPninetyfive{tag}"] = f"{w95}/{len(ts)}"
            macros[f"PairCommits{tag}"] = f"{wc}/{len(ts)}"
    write("paired.tex", "".join(rows))

    # latency of the fixed-interval curve at ACS's commit count (linear between neighbours)
    for k in ("1", "2"):
        pts = sorted((med([r.get("n_batch_commits") for r in by[k][st]]), med([m_lat(r, "p50_s") for r in by[k][st]]))
                     for st in ORDER if not st.startswith("ACS"))
        for st in ("ACS v1", "ACS v2"):
            c = med([r.get("n_batch_commits") for r in by[k][st]])
            for (c0, l0), (c1, l1) in zip(pts, pts[1:]):
                if c0 <= c <= c1:
                    macros[f"Curve{MACRO_NAME[st]}{'One' if k == '1' else 'Two'}"] = \
                        f"{l0 + (l1 - l0) * (c - c0) / (c1 - c0):.2f}"

    # replay events (both runs)
    rows, n_rep, n_clean = [], 0, 0
    for k in ("1", "2"):
        for r in clean[k]:
            n_clean += 1
            ak = r.get("at_kill") or {}
            if (ak.get("replay_records") or 0) > 0:
                n_rep += 1
                rows.append((k, label(r["config"]), r["config"]["trial"], ak["replay_records"],
                             r["events"].get("recovery_latency_s"), r["committed"]["duplicate_rows"]))
    rows.sort(key=lambda x: (x[0], x[3]))
    write("replay.tex", "".join(
        f"{k} & {SHORT[st]} & {t} & {rep:,} & {rec:.1f} & {dup:,} \\\\\n".replace(",", "{,}")
        for k, st, t, rep, rec, dup in rows))
    dup_trials = [r for k in clean for r in clean[k] if r["committed"]["duplicate_rows"] > 0]

    # recovery split (second run) and modes (both runs)
    rows = []
    for st in ORDER:
        sp = [restart_split(r) for r in by["2"][st]]
        sp = [x for x in sp if x]
        rows.append(f"{SHORT[st]} & {len(sp)} & {rng([x[0] for x in sp], '{:.1f}')} & "
                    f"{rng([x[1] for x in sp], '{:.1f}')} \\\\\n")
    write("recovery_split.tex", "".join(rows))
    allrec = [r["events"]["recovery_latency_s"] for k in clean for r in clean[k]
              if r["events"].get("recovery_latency_s")]
    sh2 = [x for x in (startup_share(r) for k in clean for r in clean[k]) if x is not None]
    macros["ACSStartupShareMed"] = f"{100 * statistics.median(sh2):.0f}"
    fast = [restart_split(r) for k in clean for r in clean[k]
            if r["events"].get("recovery_latency_s") and r["events"]["recovery_latency_s"] < 12]
    slow = [restart_split(r) for k in clean for r in clean[k]
            if r["events"].get("recovery_latency_s") and 12 <= r["events"]["recovery_latency_s"] < 17]
    fast, slow = [x for x in fast if x], [x for x in slow if x]
    macros.update({"FastStartup": f"{med([x[0] for x in fast]):.1f}", "FastFirst": f"{med([x[1] for x in fast]):.1f}",
                   "SlowStartup": f"{med([x[0] for x in slow]):.1f}", "SlowFirst": f"{med([x[1] for x in slow]):.1f}"})

    # stalls
    rows = []
    for r in sorted(stalled["2"] + stalled["1"], key=lambda r: r["run_id"]):
        rows.append(f"{r['run_id'][:16]} & {SHORT[label(r['config'])]} & {r['config']['trial']} & "
                    f"{producer_overrun(r):.0f} \\\\\n")
    write("stalls.tex", "".join(rows))
    overs = [producer_overrun(r) for k in runs for r in runs[k] if producer_overrun(r) is not None]

    # switches
    acs = [r for k in clean for r in clean[k] if r["config"]["strategy"] == "ACS"]
    downs = []
    for r in acs:
        try:
            with open(os.path.join(r["_dir"], "control.jsonl"), encoding="utf-8") as f:
                for line in f:
                    e = json.loads(line)
                    if e["type"] == "first_batch_after_switch":
                        downs.append(e["downtime_s"])
        except OSError:
            pass
    nsw = sum((r.get("control") or {}).get("switches") or 0 for r in acs)

    allacs = [r for k in runs for r in runs[k]]
    commits = sorted({r["environment"]["git_commit"][:7] for r in allacs})
    dirty = sum(bool(r["environment"].get("git_dirty")) for r in allacs + s1)
    macros.update({
        "ACSTrialsOne": len(runs["1"]), "ACSTrialsTwo": len(runs["2"]),
        "ACSCleanOne": len(clean["1"]), "ACSCleanTwo": len(clean["2"]),
        "ACSStalled": len(stalled["1"]) + len(stalled["2"]),
        "ACSCommits": ", ".join(commits), "DirtyTrials": dirty,
        "AllTrials": len(s1) + len(allacs),
        "OverrunUnderOne": sum(o <= 1 for o in overs), "OverrunTotal": len(overs),
        "ReplayEvents": n_rep, "CleanTrials": n_clean, "DupTrials": len(dup_trials),
        "DupRows": f"{sum(r['committed']['duplicate_rows'] for r in dup_trials):,}".replace(",", "{,}"),
        "ACSTrialsClean": len(acs), "Switches": nsw, "SwitchN": len(downs),
        "SwitchMed": f"{statistics.median(downs):.2f}", "SwitchMin": f"{min(downs):.2f}",
        "SwitchMax": f"{max(downs):.2f}",
        "SwitchOverOne": sum(d > 1.0 for d in downs),
        "RecFast": sum(x < 12 for x in allrec), "RecSlow": sum(12 <= x < 17 for x in allrec),
        "RecOutlier": sum(x >= 17 for x in allrec), "RecAll": len(allrec),
        "ACSDupTrials": sum(r["committed"]["duplicate_rows"] > 0 for r in acs),
    })
    for k in ("1", "2"):
        for st in ORDER:
            key = MACRO_NAME[st] + ("One" if k == "1" else "Two")
            ts = by[k][st]
            macros[f"Pfifty{key}"] = f"{med([m_lat(r, 'p50_s') for r in ts]):.2f}"
            macros[f"Pninetyfive{key}"] = f"{med([m_lat(r, 'p95_s') for r in ts]):.2f}"
            macros[f"Commits{key}"] = f"{med([r.get('n_batch_commits') for r in ts]):.0f}"
            mi = [(r.get("control") or {}).get("time_weighted_interval_s") for r in ts]
            if any(mi):
                macros[f"Interval{key}"] = f"{med(mi):.1f}"
    write("macros.tex", "".join(
        f"\\newcommand{{\\{''.join(c for c in k if c.isalpha())}}}{{{v}}}\n" for k, v in macros.items()))
    print(f"wrote {len(os.listdir(OUT))} files to {OUT}")
    for k, v in macros.items():
        print(f"  {k} = {v}")


if __name__ == "__main__":
    main()
